/** Проста перевірка адреси — без надмірної суворості, щоб не відсікати живі скриньки. */
export function isValidEmail(raw: string): boolean {
  const s = (raw || '').trim();
  if (s.length < 6 || s.length > 254) return false;
  return /^[^\s@]+@[^\s@.]+(\.[^\s@.]+)+$/.test(s);
}
